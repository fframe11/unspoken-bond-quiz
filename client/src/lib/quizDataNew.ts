export function calculateMBTI(scores: {
  E: number;
  S: number;
  T: number;
  J: number;
}): string {
  const e_i = scores.E >= 2.5 ? "E" : "I";
  const s_n = scores.S >= 2.5 ? "S" : "N";
  const t_f = scores.T >= 2.5 ? "T" : "F";
  const j_p = scores.J >= 2.5 ? "J" : "P";

  return `${e_i}${s_n}${t_f}${j_p}`;
}

